from _draw import Canvas, SYM, NEU, EXT, STO, WHITE


def build(out):
    c = Canvas(16.5, 14.3, y0=0.9)

    # --- контур оркестратора ------------------------------------------------
    CX0, CX1 = 4.2, 10.25
    c.rect(CX0, 2.6, CX1, 15.0, style=dict(fc="#f6f8fb", ec="#1f3a5f"), ls="--", z=0)
    c.text((CX0 + CX1) / 2, 14.6, "Оркестратор (агентный цикл,\nавтомат состояний инцидента)",
           fs=8.2, bold=True, bg=False)

    X1, W1, H1 = 7.25, 5.2, 1.25
    ys = [13.45, 11.75, 10.05, 8.35, 6.65, 4.95, 3.25]
    steps = [
        ("Детектор инцидентов", "правила и паттерны логов\n+ Isolation Forest", SYM),
        ("Сборщик контекста", "окно метрик, строки логов,\nсигналы", SYM),
        ("Диагност (RAG)", "запрос → поиск → LLM →\nгипотезы", NEU),
        ("Верификатор", "схема, источники, согласованность,\nрасчёт уверенности C", SYM),
        ("Движок политик", "продукционные правила,\nкласс риска действия", SYM),
        ("Исполнитель действий", "реестр, идемпотентность,\nтаймаут, песочница", SYM),
        ("Проверка результата", "критерии успеха из runbook;\nиначе — следующая гипотеза", SYM),
    ]
    for (t, sub, st), y in zip(steps, ys):
        c.box(X1, y, W1, H1, t, style=st, bold=True, sub=sub, fs=9.2, fs_sub=7.8)
    for a, b in zip(ys[:-1], ys[1:]):
        c.line([(X1, a - H1 / 2), (X1, b + H1 / 2)])
    for label, (a, b) in zip(("И2", "И3", "И6", "И7", "И8"), zip(ys[:5], ys[1:6])):
        c.marker(X1 + 0.55, (a + b) / 2, label)

    # --- левая колонка: демо-сервис -----------------------------------------
    c.box(1.75, 8.4, 3.1, 11.4, "", style=EXT)
    c.text(1.75, 13.6, "Демо-сервис", fs=9.5, bold=True, bg=False)
    for y, t in ((12.0, "FastAPI:\nприкладной API"), (10.4, "RabbitMQ:\nочередь задач"),
                 (8.8, "Celery:\nпул воркеров"), (7.2, "PostgreSQL:\nданные сервиса")):
        c.box(1.75, y, 2.6, 1.0, t, style=WHITE, fs=8.2)
    c.box(1.75, 5.6, 2.6, 1.0, "Инжектор сбоев\n(по кнопке)", style=WHITE, fs=8.2, ls="--")
    c.text(1.75, 3.75, "метрики и логи:\nдлина очереди, доля\nошибок, p95, воркеры", fs=7.6, bg=False)

    # И1: телеметрия -> детектор
    c.line([(3.3, 13.45), (X1 - W1 / 2, 13.45)])
    c.marker(3.75, 13.85, "И1")
    # И9: команды и метрики проверки
    c.line([(X1 - W1 / 2, 4.95), (3.3, 4.95)])
    c.line([(3.3, 3.25), (X1 - W1 / 2, 3.25)], ls="--", lw=0.9)
    c.marker(3.75, 4.1, "И9")

    # --- правая колонка ------------------------------------------------------
    XR, WR = 13.6, 5.0
    c.box(XR, 12.65, WR, 1.1, "База знаний", style=STO, bold=True,
          sub="runbook-инструкции (Markdown),\nсловари сигналов и действий", fs=9.2, fs_sub=7.8)
    c.box(XR, 10.8, WR, 1.25, "Гибридный поиск", style=NEU, bold=True,
          sub="BM25 и векторный поиск,\nслияние RRF, модель эмбеддингов", fs=9.2, fs_sub=7.8)
    c.box(XR, 9.1, WR, 1.25, "Сервер языковой модели", style=NEU, bold=True,
          sub="локальный инференс (Ollama),\nответ в формате JSON по схеме", fs=9.2, fs_sub=7.8)
    c.box(XR, 6.65, WR, 1.25, "Интерфейс дежурного", style=SYM, bold=True,
          sub="REST API и веб-панель: карточка,\nподтверждение, аудит", fs=9.2, fs_sub=7.8)
    c.box(XR, 3.25, WR, 1.25, "Журнал аудита", style=STO, bold=True,
          sub="PostgreSQL: инциденты, события,\nхэш-цепочка записей", fs=9.2, fs_sub=7.8)

    c.line([(XR, 10.8 + 0.625), (XR, 12.65 - 0.55)], both=True)
    c.line([(X1 + W1 / 2, 10.35), (XR - WR / 2, 10.35)], both=True)
    c.marker(10.65, 10.77, "И4")
    c.line([(X1 + W1 / 2, 9.6), (XR - WR / 2, 9.6)], both=True)
    c.marker(10.65, 9.18, "И5")
    c.line([(XR - WR / 2, 6.65), (CX1, 6.65)], both=True)
    c.marker(10.7, 7.07, "И10")
    c.line([(CX1, 3.25), (XR - WR / 2, 3.25)])
    c.marker(10.7, 3.67, "И11")

    # --- легенда (в одну строку) ---------------------------------------------------
    x = 0.4
    for st, t, wlab in ((SYM, "символьный компонент", 3.3), (NEU, "нейробионический компонент", 4.1),
                        (STO, "хранилище знаний и данных", 3.9), (EXT, "внешняя система", 2.4)):
        c.rect(x, 1.5, x + 0.55, 1.9, style=st, lw=0.9, z=2)
        c.text(x + 0.7, 1.7, t, fs=8, ha="left", bg=False)
        x += 0.7 + wlab
    c.save(out)


if __name__ == "__main__":
    import sys
    build(sys.argv[1])
